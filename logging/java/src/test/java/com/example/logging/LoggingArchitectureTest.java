package com.example.logging;

import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses;

import com.tngtech.archunit.core.importer.ImportOption;
import com.tngtech.archunit.junit.AnalyzeClasses;
import com.tngtech.archunit.junit.ArchTest;
import com.tngtech.archunit.lang.ArchRule;
import com.tngtech.archunit.library.GeneralCodingRules;

/**
 * Bans raw logging in production code. Set {@code packages} to the project's root package.
 */
@AnalyzeClasses(packages = "com.example", importOptions = ImportOption.DoNotIncludeTests.class)
class LoggingArchitectureTest {

    /** System.out, System.err and Throwable.printStackTrace(). */
    @ArchTest
    static final ArchRule no_standard_streams = GeneralCodingRules.NO_CLASSES_SHOULD_ACCESS_STANDARD_STREAMS;

    /** Covers LoggerFactory.getLogger(...) written by hand and generated by Lombok's @Slf4j. */
    @ArchTest
    static final ArchRule no_direct_logger_factory = noClasses()
            .that().resideOutsideOfPackage("com.example.logging..")
            .should().dependOnClassesThat().haveFullyQualifiedName("org.slf4j.LoggerFactory")
            .because("all logging goes through com.example.logging.TaggedLogger so every entry carries tags")
            .allowEmptyShould(true); // passes in a fresh project with no classes outside the logging package yet
}
